import "server-only"
import { and, eq, inArray, isNull, sql } from "drizzle-orm"
import { db } from "@/lib/db"
import {
  garageSettings,
  garages,
  memberships,
  notifications,
  parts,
  purchaseOrderItems,
  purchaseOrders,
  stockLevels,
  vendorProducts,
  vendors,
} from "@/lib/db/schema"
import { nextDocNumber } from "@/lib/money/sequence"
import { uuidv7 } from "@/lib/id"

const OPEN_PO_STATUSES = ["draft", "pending_approval", "sent", "accepted", "partially_delivered"] as const

export type LowStockCandidate = {
  stockLevelId: string
  garageId: string
  branchId: string
  partId: string
  partName: string
  sku: string
  quantityOnHand: number
  reorderLevel: number
  reorderQuantity: number
  preferredVendorId: string | null
  preferredVendorProductId: string | null
  averageCost: bigint
}

/** Parts at/below reorder level that have a preferred vendor and no open auto PO. */
export async function findLowStockCandidates(garageId?: string): Promise<LowStockCandidate[]> {
  const rows = await db()
    .select({
      stockLevelId: stockLevels.id,
      garageId: stockLevels.garageId,
      branchId: stockLevels.branchId,
      partId: stockLevels.partId,
      quantityOnHand: stockLevels.quantityOnHand,
      reorderLevel: stockLevels.reorderLevel,
      reorderQuantity: stockLevels.reorderQuantity,
      averageCost: stockLevels.averageCost,
      partName: parts.name,
      sku: parts.sku,
      preferredVendorId: parts.preferredVendorId,
      preferredVendorProductId: parts.preferredVendorProductId,
      isActive: parts.isActive,
    })
    .from(stockLevels)
    .innerJoin(parts, eq(stockLevels.partId, parts.id))
    .where(and(
      garageId ? eq(stockLevels.garageId, garageId) : undefined,
      eq(parts.isActive, true),
      sql`${stockLevels.reorderLevel}::numeric > 0`,
      sql`${stockLevels.quantityOnHand}::numeric <= ${stockLevels.reorderLevel}::numeric`,
    ))

  const candidates = rows.filter((r) => r.preferredVendorId != null)
  if (candidates.length === 0) return []

  // exclude parts that already have an open auto-generated PO
  const partIds = candidates.map((c) => c.partId)
  const openItems = await db()
    .select({ partId: purchaseOrderItems.partId })
    .from(purchaseOrderItems)
    .innerJoin(purchaseOrders, eq(purchaseOrderItems.purchaseOrderId, purchaseOrders.id))
    .where(and(
      inArray(purchaseOrderItems.partId, partIds),
      eq(purchaseOrders.isAutoGenerated, true),
      inArray(purchaseOrders.status, [...OPEN_PO_STATUSES]),
    ))
  const covered = new Set(openItems.map((i) => i.partId))

  return candidates
    .filter((c) => !covered.has(c.partId))
    .map((c) => ({
      stockLevelId: c.stockLevelId,
      garageId: c.garageId,
      branchId: c.branchId,
      partId: c.partId,
      partName: c.partName,
      sku: c.sku,
      quantityOnHand: Number(c.quantityOnHand),
      reorderLevel: Number(c.reorderLevel),
      reorderQuantity: Number(c.reorderQuantity),
      preferredVendorId: c.preferredVendorId,
      preferredVendorProductId: c.preferredVendorProductId,
      averageCost: c.averageCost ?? 0n,
    }))
}

async function unitCostFor(c: LowStockCandidate): Promise<bigint> {
  if (c.preferredVendorProductId) {
    const [vp] = await db().select({ price: vendorProducts.price }).from(vendorProducts)
      .where(eq(vendorProducts.id, c.preferredVendorProductId)).limit(1)
    if (vp) return vp.price
  }
  return c.averageCost
}

function orderQty(c: LowStockCandidate): number {
  if (c.reorderQuantity > 0) return Math.ceil(c.reorderQuantity)
  return Math.max(1, Math.ceil(c.reorderLevel - c.quantityOnHand))
}

/**
 * Nightly/on-movement auto-reorder. Creates one draft (or auto-sent) PO per
 * (branch, vendor) group. Respects garageSettings.autoReorderEnabled and
 * autoReorderSpendLimit; notifies owner/manager when a draft needs approval.
 */
export async function runAutoReorderForGarage(garageId: string) {
  const candidates = await findLowStockCandidates(garageId)
  if (candidates.length === 0) return { created: 0, sent: 0, notified: 0, skipped: 0 }

  const [settings] = await db().select().from(garageSettings).where(eq(garageSettings.garageId, garageId)).limit(1)
  const [garage] = await db().select({ slug: garages.slug, name: garages.name }).from(garages)
    .where(eq(garages.id, garageId)).limit(1)
  if (!garage) return { created: 0, sent: 0, notified: 0, skipped: 0 }

  const autoEnabled = settings?.autoReorderEnabled === true
  const spendLimit = settings?.autoReorderSpendLimit ?? 0n

  // group by branch+vendor
  const groups = new Map<string, LowStockCandidate[]>()
  for (const c of candidates) {
    const key = `${c.branchId}:${c.preferredVendorId}`
    groups.set(key, [...(groups.get(key) ?? []), c])
  }

  // only order from approved vendors
  const vendorIds = [...new Set(candidates.map((c) => c.preferredVendorId!))]
  const approved = await db().select({ id: vendors.id }).from(vendors)
    .where(and(inArray(vendors.id, vendorIds), eq(vendors.status, "approved"), isNull(vendors.deletedAt)))
  const approvedSet = new Set(approved.map((v) => v.id))

  let created = 0, sent = 0, notified = 0, skipped = 0

  for (const [, group] of groups) {
    const vendorId = group[0]!.preferredVendorId!
    if (!approvedSet.has(vendorId)) { skipped += group.length; continue }
    const branchId = group[0]!.branchId

    const lines: { partId: string; qty: number; unitCost: bigint; name: string }[] = []
    for (const c of group) {
      lines.push({ partId: c.partId, qty: orderQty(c), unitCost: await unitCostFor(c), name: c.partName })
    }
    const total = lines.reduce((s, l) => s + BigInt(l.qty) * l.unitCost, 0n)

    const autoSend = autoEnabled && total <= spendLimit
    const number = await nextDocNumber(garageId, branchId, "PO", "PO")
    const poId = uuidv7()

    await db().insert(purchaseOrders).values({
      id: poId, garageId, branchId, number, vendorId,
      status: autoSend ? "sent" : "draft",
      isAutoGenerated: true,
      subtotal: total, total,
      notes: `Auto-reorder: ${lines.map((l) => `${l.name} ×${l.qty}`).join(", ")}`,
      ...(autoSend ? { approvedAt: new Date() } : {}),
    })
    for (const l of lines) {
      await db().insert(purchaseOrderItems).values({
        id: uuidv7(), garageId, purchaseOrderId: poId, partId: l.partId,
        vendorProductId: group.find((g) => g.partId === l.partId)?.preferredVendorProductId ?? null,
        quantity: String(l.qty), unitCost: l.unitCost,
      })
    }
    created++
    if (autoSend) { sent++; continue }

    // notify owner/manager members — one-tap approval needed
    const managers = (await db().select({ userId: memberships.userId }).from(memberships)
      .where(and(eq(memberships.garageId, garageId), inArray(memberships.role, ["owner", "manager"]), eq(memberships.status, "active"))))
      .map((m) => m.userId).filter((id): id is string => id != null)
    for (const userId of managers) {
      await db().insert(notifications).values({
        garageId, userId,
        kind: "low_stock",
        title: `Reorder suggested: ${lines.length} part${lines.length > 1 ? "s" : ""}`,
        body: `${number} — ${lines.map((l) => l.name).join(", ")} (total GH₵${(Number(total) / 100).toFixed(2)})`,
        link: `/g/${garage.slug}/purchase-orders`,
      })
      notified++
    }
  }

  return { created, sent, notified, skipped }
}

/** Nightly sweep across all garages. */
export async function runAutoReorderAll() {
  const all = await db().select({ id: garages.id }).from(garages).where(isNull(garages.deletedAt))
  let created = 0, sent = 0, notified = 0
  for (const g of all) {
    const r = await runAutoReorderForGarage(g.id)
    created += r.created; sent += r.sent; notified += r.notified
  }
  return { garages: all.length, created, sent, notified }
}

